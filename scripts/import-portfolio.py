#!/usr/bin/env python3
"""
Import docs/portfolio-manifest.json into src/content/work.generated.ts.

Run from the repo root after adding or changing portfolio images:
    python3 scripts/import-portfolio.py

- Reads real pixel dimensions from each file (Pillow), so next/image gets correct sizes.
- Groups images by project; hero image first.
- Publishes only public-safe fields. `scopeNote` is internal and is NEVER written out.
- Client names are kept only when clientPublic is true.
"""
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs" / "portfolio-manifest.json"
OUT = ROOT / "src" / "content" / "work.generated.ts"

data = json.loads(MANIFEST.read_text())
projects: dict[str, dict] = {}
missing = []

for item in data["images"]:
    rel = item["path"]
    f = ROOT / rel
    if not f.exists():
        missing.append(rel)
        continue
    with Image.open(f) as im:
        w, h = im.size
    name = item["project"]
    m = re.match(r"public/(?:work/)?([^/]+)/", rel)
    folder = m.group(1) if m else re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    p = projects.setdefault(
        name,
        {
            "name": name,
            "folder": folder,
            "category": item["category"],
            "year": item.get("year"),
            "scope": item.get("scope") or [],
            "client": item.get("client") if item.get("clientPublic") else None,
            "credit": item.get("credit"),
            "signature": bool(item.get("signature")),
            "youtubeIds": [],
            "images": [],
        },
    )
    p["year"] = p["year"] or item.get("year")
    p["signature"] = p["signature"] or bool(item.get("signature"))
    yt = item.get("youtubeId")
    if yt and yt not in p["youtubeIds"]:
        p["youtubeIds"].append(yt)
    p["images"].append(
        {
            "src": "/" + rel.removeprefix("public/"),
            "width": w,
            "height": h,
            "alt": item["alt"].strip(),
            "title": item.get("title") or "",
            "hero": bool(item.get("hero")),
        }
    )

for p in projects.values():
    p["images"].sort(key=lambda i: (not i["hero"], i["src"]))

walk = data.get("walkthrough")
skyframe_video = None
if walk and (ROOT / walk["path"]).exists():
    skyframe_video = "/" + walk["path"].removeprefix("public/")

header = (
    "/* AUTO-GENERATED by scripts/import-portfolio.py from docs/portfolio-manifest.json. Do not edit by hand. */\n"
    "export type ManifestImage = { src: string; width: number; height: number; alt: string; title: string; hero: boolean };\n"
    "export type ManifestProject = {\n"
    "  name: string; folder: string; category: string; year: number | null; scope: string[];\n"
    "  client: string | null; credit: string | null; signature: boolean; youtubeIds: string[]; images: ManifestImage[];\n"
    "};\n"
)
body = (
    f"export const manifestProjects: ManifestProject[] = {json.dumps(list(projects.values()), indent=2, ensure_ascii=False)};\n\n"
    f"export const skyframeWalkthrough: string | null = {json.dumps(skyframe_video)};\n"
)
OUT.write_text(header + "\n" + body)

n = sum(len(p["images"]) for p in projects.values())
print(f"Wrote {OUT.relative_to(ROOT)}: {len(projects)} projects, {n} images.")
if missing:
    print(f"WARNING: {len(missing)} files listed in the manifest are missing, e.g. {missing[:3]}", file=sys.stderr)
